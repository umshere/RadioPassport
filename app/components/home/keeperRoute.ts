/** One artist, one dedicated live stream, one stable page about them. */
function artistRoute({
  id,
  group,
  artist,
  wiki,
  name,
  station,
}: {
  id: string;
  group: KeeperGroup;
  artist: string;
  wiki: string;
  name: string;
  station: Station;
}): KeeperRoute {
  return {
    id,
    group,
    label: artist,
    title: VOICE.homeKeeperRouteArtistTitle(artist),
    intro: VOICE.homeKeeperRouteArtistIntro,
    stops: [
      {
        station,
        name,
        reason: VOICE.homeKeeperRouteArtistReason(artist),
        sourceLabel: VOICE.homeKeeperRouteArtistSource(artist),
        sourceUrl: `https://en.wikipedia.org/wiki/${wiki}`,
      },
    ],
  };
}

